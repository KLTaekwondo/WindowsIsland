    [DllImport("user32.dll", SetLastError = true)]
    [return: MarshalAs(UnmanagedType.Bool)]
    public static extern bool UnregisterHotKey(IntPtr hWnd, int id);

    /// <summary>Window class names that the shell uses for the desktop surface.</summary>
    public static bool IsShellDesktopClass(string? className)
        => className is "Progman" or "WorkerW" or "SHELLDLL_DefView" or "SysListView32";

    public static string GetClassNameSafe(IntPtr hwnd)
    {
        if (hwnd == IntPtr.Zero)
        {
            return string.Empty;
        }

        var buffer = new StringBuilder(256);
        return GetClassName(hwnd, buffer, buffer.Capacity) > 0 ? buffer.ToString() : string.Empty;
    }
}
